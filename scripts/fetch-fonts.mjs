// One-time font fetcher: downloads exact font subsets from Google Fonts and
// writes src/fonts.css + assets/fonts/*.woff2 so the extension is fully
// offline-capable and avoids any remote-code/CSP concerns.
//
// Fonts:
//  - Quicksand (latin + latin-ext) 300..700  — dashboard body font
//  - Noto Serif JP (400/700/900) subset to the glyphs actually rendered —
//    greetings, clock digits, AM/PM, kanji watermarks.
//
// Usage: npm run deps:fonts  (or: node scripts/fetch-fonts.mjs)

import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FONTS_DIR = path.join(ROOT, 'assets', 'fonts');
const CSS_OUT = path.join(ROOT, 'src', 'fonts.css');

const CSS_UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';

// Characters the JP decorative font must cover.
const JP_TEXT =
  'おはようこんにちはんばやすみ和野名0123456789:APM';

const cssUrlFor = (family, weights, text = '') =>
  'https://fonts.googleapis.com/css2?' +
  `family=${family}:wght@${weights}&display=swap${text ? `&text=${encodeURIComponent(text)}` : ''}`;

async function fetchCss(family, weights, text = '') {
  const res = await fetch(cssUrlFor(family, weights, text), { headers: { 'User-Agent': CSS_UA } });
  if (!res.ok) throw new Error(`Google Fonts CSS ${res.status} for ${family}`);
  return res.text();
}

function parseFaces(css) {
  const faces = [];
  const re = /\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*{([^}]+)}/g;
  let m;
  while ((m = re.exec(css))) {
    const body = m[2];
    faces.push(faceFromBody(body, m[1]));
  }
  return faces.filter(Boolean);
}

// css2 fallback (text-subset responses may lack subset comments).
function parseFacesNoSubsets(css) {
  const faces = [];
  const re = /@font-face\s*{([^}]+)}/g;
  let m;
  while ((m = re.exec(css))) faces.push(faceFromBody(m[1], 'text'));
  return faces.filter(Boolean);
}

const rangeRe = /unicode-range:\s*([^;]+);/;

function faceFromBody(body, subset) {
  const family = /font-family:\s*'([^']+)'/.exec(body)?.[1];
  const weight = /font-weight:\s*(\d+)/.exec(body)?.[1];
  const style = /font-style:\s*(\w+)/.exec(body)?.[1] || 'normal';
  const url = /url\((https:[^)]+)\)\s*format\('woff2'\)/.exec(body)?.[1];
  const range = rangeRe.exec(body)?.[1];
  if (!family || !weight || !url) return null;
  return { family, weight, style, subset, url, range: range?.trim() };
}

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

async function downloadFaces(faces, keep) {
  const kept = faces.filter(keep);
  const cssBlocks = [];
  let total = 0;
  for (const face of kept) {
    const name = `${slug(face.family)}-${face.weight}${face.subset !== 'text' ? `-${face.subset}` : ''}.woff2`;
    const res = await fetch(face.url, { headers: { 'User-Agent': CSS_UA } });
    if (!res.ok) throw new Error(`Font download ${res.status}: ${face.url}`);
    const buf = Buffer.from(await res.arrayBuffer());
    await writeFile(path.join(FONTS_DIR, name), buf);
    total += buf.length;
    cssBlocks.push(
      `@font-face {\n  font-family: '${face.family}';\n  font-style: ${face.style};\n  font-weight: ${face.weight};\n  font-display: swap;\n  src: url('../assets/fonts/${name}') format('woff2');${face.range ? `\n  unicode-range: ${face.range};` : ''}\n}`
    );
    console.log(`  ✓ ${name} (${(buf.length / 1024).toFixed(1)} KB)`);
  }
  return { css: cssBlocks.join('\n\n'), total, count: kept.length };
}

await mkdir(FONTS_DIR, { recursive: true });

console.log('Fetching Quicksand (latin subsets, 300..700)...');
const quicksandCss = await fetchCss('Quicksand', '300;400;500;600;700');
const a = await downloadFaces(parseFaces(quicksandCss), (f) => ['latin', 'latin-ext'].includes(f.subset));

console.log('Fetching Noto Serif JP (subset glyphs, 400/700/900)...');
const notoCss = await fetchCss('Noto Serif JP', '400;700;900', JP_TEXT);
const b = await downloadFaces(parseFacesNoSubsets(notoCss), () => true);

const banner = `/* Self-hosted fonts (generated by scripts/fetch-fonts.mjs — do not edit by hand). */\n\n`;
const note = `\n/* NOTE: Noto Serif JP faces above are pre-subset to exactly the glyphs the\n   dashboard renders (greetings, clock digits, kanji watermarks). If you add\n   new Japanese UI text, re-run the font script to include those glyphs. */\n`;
await writeFile(CSS_OUT, banner + a.css + '\n\n' + b.css + note);
console.log(`\nDone — ${a.count + b.count} files, ${(total(a, b) / 1024).toFixed(1)} KB total → src/fonts.css`);

function total(...groups) {
  return groups.reduce((acc, g) => acc + g.total, 0);
}
